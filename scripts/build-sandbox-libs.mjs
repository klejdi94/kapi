// Bundles the libraries Postman scripts commonly require() into self-contained
// source strings, written to src/lib/scripting/sandboxLibs.generated.js.
//
// They have to be *source*, not modules imported by the host: the script
// sandbox evaluates them inside its own realm (a Web Worker, or a fresh
// node:vm context), so nothing a script gets back from require() was created
// in the host's realm — a host-realm function would be a way out of the
// sandbox (`fn.constructor.constructor('return process')()`).
//
// Runs on `npm install` (postinstall) and before builds; the output is not committed.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'lib', 'scripting', 'sandboxLibs.generated.js');

const LIBS = {
  lodash: "module.exports = require('lodash');",
  'crypto-js': "module.exports = require('crypto-js');",
  moment: "module.exports = require('moment');",
  uuid: "module.exports = require('uuid');",
  xml2js: "module.exports = require('xml2js');",
};

const sources = {};
for (const [name, entry] of Object.entries(LIBS)) {
  const result = await build({
    stdin: { contents: entry, resolveDir: root, sourcefile: `${name}-entry.js` },
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__kapiLib',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    logLevel: 'error',
    alias: {
      timers: join(root, 'scripts', 'shims', 'timers.cjs'),
      stream: join(root, 'scripts', 'shims', 'stream.cjs'),
      events: join(root, 'node_modules', 'events', 'events.js'),
      string_decoder: join(root, 'node_modules', 'string_decoder', 'lib', 'string_decoder.js'),
      buffer: join(root, 'node_modules', 'buffer', 'index.js'),
    },
    // crypto-js probes for a native crypto module; the sandbox uses its Math.random fallback… unless
    // WebCrypto is there (the worker has it), which crypto-js picks up from globalThis.crypto.
    external: ['crypto'],
    define: { global: 'globalThis' },
  });
  sources[name] = result.outputFiles[0].text;
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// Generated by scripts/build-sandbox-libs.mjs — do not edit.\n' +
    '/** @type {Record<string, string>} */\n' +
    `export const SANDBOX_LIB_SOURCES = ${JSON.stringify(sources)};\n`,
);
const kb = Object.fromEntries(Object.entries(sources).map(([k, v]) => [k, `${Math.round(v.length / 1024)}KB`]));
console.log('sandbox libraries:', kb);
