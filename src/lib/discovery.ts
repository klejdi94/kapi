import { invoke } from '@tauri-apps/api/core';
import { listen, type UnlistenFn } from '@tauri-apps/api/event';
import type { Collection, Environment, TreeNode } from '@/types';
import { emptyAuth, kv, newCollection, newEnvironment, newFolder, newRequestNode, withTrailingBlank } from './factory';
import { isDesktop } from './transport';

/** One HTTP call captured by the discovery window's fetch/XHR patch — see `src-tauri/src/discovery.rs`. */
export interface CapturedCall {
  method: string;
  url: string;
  status: number | null;
  requestHeaders: [string, string][];
  responseContentType: string;
  at: number;
}

/** Headers the capture script never lets through with a real value — see the same denylist there. */
const REDACTED = '<redacted>';
/** Regenerated by kapi itself, or too connection-specific to carry over. */
const DROP_HEADERS = new Set(['content-length', 'host', 'connection', 'accept-encoding', 'user-agent', 'accept', 'referer', 'origin']);
/** Responses that are almost never the API itself — markup, styling, static assets. */
const NON_API_CONTENT_TYPES = ['text/html', 'text/css', 'font/', 'image/', 'video/', 'audio/'];

export function discoveryAvailable(): boolean {
  return isDesktop();
}

export async function openDiscoveryWindow(url: string): Promise<void> {
  await invoke('kapi_open_discovery', { url });
}

export function onDiscoveryCapture(handler: (entries: CapturedCall[]) => void): Promise<UnlistenFn> {
  return listen<CapturedCall[]>('kapi://discovery-capture', (event) => handler(event.payload));
}

/** `/users/123` and `/users/8f14e...` (uuid) both become `/users/:id` — the same
 * templating idea `pathVariableNames`/OpenAPI import use, run in reverse. */
function templateSegment(segment: string): string {
  if (/^\d+$/.test(segment)) return ':id';
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(segment)) return ':id';
  if (/^[0-9a-f]{24}$/i.test(segment)) return ':id';
  return segment;
}

export function templatePath(pathname: string): string {
  return pathname.split('/').map(templateSegment).join('/') || '/';
}

export interface DiscoveredEndpoint {
  id: string;
  method: string;
  host: string;
  path: string;
  hits: number;
  status: number | null;
  requestHeaders: [string, string][];
  responseContentType: string;
  queryParamNames: string[];
  lastSeenAt: number;
}

/** Collapses raw captures into unique templated endpoints, most-recently-seen first within each host+path. */
export function groupCaptures(entries: CapturedCall[]): DiscoveredEndpoint[] {
  const byKey = new Map<string, DiscoveredEndpoint>();
  for (const entry of entries) {
    let parsed: URL;
    try {
      parsed = new URL(entry.url);
    } catch {
      continue;
    }
    if (!/^https?:$/.test(parsed.protocol)) continue;
    if (NON_API_CONTENT_TYPES.some((t) => entry.responseContentType.startsWith(t))) continue;

    const path = templatePath(parsed.pathname);
    const key = `${entry.method} ${parsed.host}${path}`;
    const paramNames = [...parsed.searchParams.keys()];
    const existing = byKey.get(key);
    if (existing) {
      existing.hits += 1;
      existing.lastSeenAt = Math.max(existing.lastSeenAt, entry.at);
      if (entry.status !== null) existing.status = entry.status;
      for (const name of paramNames) if (!existing.queryParamNames.includes(name)) existing.queryParamNames.push(name);
    } else {
      byKey.set(key, {
        id: key,
        method: entry.method,
        host: parsed.host,
        path,
        hits: 1,
        status: entry.status,
        requestHeaders: entry.requestHeaders,
        responseContentType: entry.responseContentType,
        queryParamNames: paramNames,
        lastSeenAt: entry.at,
      });
    }
  }
  return [...byKey.values()].sort((a, b) => a.host.localeCompare(b.host) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

const SPEC_PATHS = ['/openapi.json', '/openapi.yaml', '/swagger.json', '/v3/api-docs', '/v2/api-docs', '/api-docs', '/swagger/v1/swagger.json'];

/**
 * Tries the handful of paths real APIs actually publish their spec at,
 * straight from the main window's native HTTP client (no CORS, no need for
 * the capture window at all) — often faster than browsing when the target
 * just... has a spec.
 */
export async function probeApiSpec(origin: string): Promise<{ url: string; text: string } | null> {
  if (!isDesktop()) return null;
  const { fetch: nativeFetch } = await import('@tauri-apps/plugin-http');
  const base = origin.replace(/\/+$/, '');
  for (const path of SPEC_PATHS) {
    const url = `${base}${path}`;
    try {
      const res = await nativeFetch(url, { method: 'GET', connectTimeout: 4000 });
      if (!res.ok) continue;
      const text = await res.text();
      if (text.trim()) return { url, text };
    } catch {
      // Try the next candidate — most of these paths 404 on any given API.
    }
  }
  return null;
}

function headerVariableName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'value';
}

/**
 * Turns the selected endpoints into a real collection — grouped into
 * per-host folders when more than one host was seen, redacted header
 * values swapped for `{{variables}}` collected into a starter environment
 * so nothing captured stays a live secret in the saved collection file.
 */
export function buildCollectionFromEndpoints(endpoints: DiscoveredEndpoint[], name: string): { collection: Collection; environment: Environment | null } {
  const collection = newCollection(name);
  const neededVars = new Set<string>();
  const byHost = new Map<string, TreeNode[]>();

  for (const ep of endpoints) {
    const node = newRequestNode(`${ep.method} ${ep.path}`);
    node.request.method = ep.method;
    node.request.url = `https://${ep.host}${ep.path}`;
    node.request.auth = emptyAuth('none');

    if (ep.queryParamNames.length) {
      node.request.params = withTrailingBlank(ep.queryParamNames.map((paramName) => kv({ key: paramName, value: '' })));
    }

    const headers = ep.requestHeaders.filter(([name]) => !DROP_HEADERS.has(name.toLowerCase()));
    if (headers.length) {
      node.request.headers = withTrailingBlank(
        headers.map(([headerName, value]) => {
          if (value !== REDACTED) return kv({ key: headerName, value });
          const varName = headerVariableName(headerName);
          neededVars.add(varName);
          return kv({ key: headerName, value: `{{${varName}}}` });
        }),
      );
    }

    node.description = `Captured ${ep.hits} time${ep.hits === 1 ? '' : 's'} while browsing${
      ep.status !== null ? ` — last response was ${ep.status}` : ''
    }${ep.responseContentType ? ` (${ep.responseContentType})` : ''}.`;

    const list = byHost.get(ep.host) ?? [];
    list.push(node);
    byHost.set(ep.host, list);
  }

  const hosts = [...byHost.entries()];
  collection.items = hosts.length <= 1 ? (hosts[0]?.[1] ?? []) : hosts.map(([host, items]) => ({ ...newFolder(host), items }));

  let environment: Environment | null = null;
  if (neededVars.size) {
    environment = newEnvironment(`${name} — auth`);
    environment.variables = withTrailingBlank([...neededVars].map((varName) => kv({ key: varName, value: '' })));
  }

  return { collection, environment };
}
